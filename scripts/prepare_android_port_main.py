"""Create a strictly reversible Android-safe entry over the MIT donor port.

This changes only the already-generated public host/main.cpp in a private
source capsule. It doesn't touch game units, the disc, the donor checkout, or
any other port source. The baseline main is generated by
scripts/prepare_external_vulkan.py --gs-stream-hooks.

The original slice200 port main was hand-edited for portable check and
headless card flush; this is a new reviewed Android variant, not a claim of
byte-identity with historical slice200. The Android CMake recipe pins the new
main separately from the three untouched slice200 port files.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
from prepare_external_vulkan import SOURCE_PINS

DONOR_COMMIT = "1b4808793a12c45125262fd2d5f50a9ec9f7c020"

# Literal, exact edits; no fuzzy matching or arbitrary regex replacements.
PATCHES = (
    (
        '#include "ps2/system.hpp"\n',
        '#include "ps2/system.hpp"\n#include "install_paths.hpp"\n',
    ),
    (
        'namespace {\n\nint usage() {\n',
        'namespace ps2::iop::sio2 { void flush_cards_now(); }\n\nnamespace {\n\nint usage() {\n',
    ),
    (
        '    if (argc < 2) return usage();\n',
        '    if (argc == 2 && std::strcmp(argv[1], "--portable-check") == 0)\n'
        '        return gt4::install::run_portable_check(std::filesystem::path(GT4_VULKAN_SHADER_DIR));\n'
        '    if (argc < 2) return usage();\n',
    ),
    (
        '    return emulate();\n',
        '    const int result = emulate();\n'
        '    ps2::iop::sio2::flush_cards_now();\n'
        '    return result;\n',
    ),
)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def replace_one(source: str, old: str, new: str) -> str:
    count = source.count(old)
    if count != 1:
        raise ValueError(f"Expected exactly one host-main patch anchor, found {count}: {old[:72]!r}")
    return source.replace(old, new, 1)


def apply(source: str) -> str:
    result = source
    for old, new in PATCHES:
        result = replace_one(result, old, new)
    back = result
    for old, new in reversed(PATCHES):
        back = replace_one(back, new, old)
    if back != source:
        raise ValueError("host main patch cannot be reversed byte-for-byte")
    return result


def expected_base(donor_text: str) -> str:
    anchor = '    register_generated_code();'
    if donor_text.count(anchor) != 1:
        raise ValueError("pinned donor main entry anchor missing")
    return donor_text.replace(
        anchor,
        '    _putenv_s("PS2_GS", "gpu");\n    register_generated_code();',
        1,
    )


def prepare(port_dir: Path, assets_root: Path) -> str:
    donor_root = assets_root / "private" / "references" / "ps2-web-recomp"
    main = donor_root / "host" / "main.cpp"
    actual_source = main.read_bytes()
    if sha256(actual_source) != SOURCE_PINS["host/main.cpp"]:
        raise ValueError("not the pinned MIT donor host/main.cpp")
    original = expected_base(actual_source.decode("utf-8").replace("\r\n", "\n"))
    port_main = port_dir / "main.cpp"
    if not port_main.is_file():
        raise ValueError("port main.cpp missing: derive the public adapter first")
    if port_main.read_text(encoding="utf-8") != original:
        raise ValueError("refusing to patch an edited / unrecognized port main.cpp")

    modified = apply(original)
    port_main.write_text(modified, encoding="utf-8", newline="\n")
    result = sha256(port_main.read_bytes())
    print(f"ANDROID_PUBLIC_PORT_MAIN_SHA256={result}")
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("port_dir", type=Path)
    parser.add_argument("--assets-root", type=Path, required=True)
    args = parser.parse_args()
    print(prepare(args.port_dir.resolve(), args.assets_root.resolve()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
